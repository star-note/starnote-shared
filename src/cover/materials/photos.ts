/**
 * Photo materials, served same-origin from `public/cover-materials/` (licences and sources in
 * `manifest.json` / `README.md` there) so modern-screenshot can rasterise them without tainting
 * the canvas. 17 AI-generated portraits (`people`) and 25 landscapes (`nature`), 15 of them chosen for colour.
 *
 * `cutout` is a foreground mask of the same image (macOS Vision, `scripts/cover/cutout.swift`):
 * the renderer stacks photo → masthead → cutout so a head, a peak or a tree rises in front of the
 * masthead letters. `cutTop` is where that foreground starts (fraction of the height).
 *
 * Hand-tuned per image on a 5% grid:
 *   - `focus`: what the crop centres on;
 *   - `faces`: [x0, y0, x1, y1] of each face, primary first — no text may cross them;
 *   - `body`: (full figures) the figure, which the main cover line avoids when it can;
 *   - `keep`: (landscapes) the subject — a tree, a lighthouse — kept clear of cover lines;
 *   - `headroom`: free sky / space above the subject (fraction of height);
 *   - `avg` / `tone` / `accent`: colours lifted from the photo for scrims and accents;
 *   - `lum`: 8×8 luminance grid (0–100, row-major; generated with sharp) so text can pick a
 *     light or dark ink for the area it sits on.
 */
export type FaceBox = [x0: number, y0: number, x1: number, y1: number];

export type ColorFamily =
  'warm' | 'gold' | 'pink' | 'purple' | 'green' | 'teal' | 'blue' | 'night' | 'mono' | 'neutral';

export interface PhotoMaterial {
  kind: 'photo';
  subject: 'people' | 'nature';
  id: string;
  label: string;
  src: string;
  cutout?: string;
  cutTop?: number;
  width: number;
  height: number;
  focus: { x: number; y: number };
  headroom: number;
  faces: FaceBox[];
  keep: FaceBox[];
  /** Landscapes: colour family (consecutive 换一张 never repeat a family) and where a title sits best. */
  family?: ColorFamily;
  zone?: 'top' | 'bottom' | 'left' | 'right' | 'center';
  /** Full figures: the body, which the main cover line prefers not to cross. */
  body?: FaceBox[];
  /** Several faces in frame: leaves no clean column for a big cover line, so 时尚杂志 skips it. */
  crowded?: boolean;
  /** Left out of 风景: the subject spans the frame, so the 1:1 / 3:4 title would cross it. */
  noScenic?: boolean;
  /** 地理志: a landscape-orientation photo with a geographic feel (mountains, coasts, deserts, ice — no flower fields). */
  geo?: boolean;
  avg: string;
  tone: string;
  accent: string;
  accentInk: string;
  lum: number[];
}

